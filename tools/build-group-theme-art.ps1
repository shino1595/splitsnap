<#
.SYNOPSIS
    Rebuilds app\src\ui\groupThemeArt.ts, the group theme drawings, in headless Microsoft Edge.

.DESCRIPTION
    tools\group-theme-art\themes.js holds the SVG source of each drawing (viewBox 244 x 96).
    tools\group-theme-art\render.html draws every theme onto a <canvas> twice, as white strokes
    ('lines') and as white fills ('fills', only the elements with class "tf"), and returns the
    two PNGs as data URIs. This script writes them into groupThemeArt.ts. The app shows each
    layer with tintColor, so the PNGs only need to be white on transparent.

.PARAMETER Scale
    Pixels per viewBox unit. 2 (default) gives 488 x 192 images; use 1.5 if the file gets too big.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File tools\build-group-theme-art.ps1
#>
[CmdletBinding()]
param([double]$Scale = 2)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'common.ps1')

$page = Join-Path $PSScriptRoot 'group-theme-art\render.html'
$target = Join-Path $script:DefaultProjectRoot 'app\src\ui\groupThemeArt.ts'
$ids = @('default', 'beach', 'mountains', 'home', 'office', 'friends', 'fitness', 'groceries', 'music', 'dining')

$lock = Enter-EdgeLock
try {
    $fragment = 'scale=' + $Scale.ToString([Globalization.CultureInfo]::InvariantCulture)
    $run = Invoke-EdgeDumpDom -HtmlPath $page -Fragment $fragment -VirtualTimeBudgetMs 20000 -TimeoutSec 90
} finally {
    Exit-EdgeLock $lock
}
$result = Get-DomJson $run.Dom 'result'
if (-not $result) { throw 'The render page produced no result.' }
$err = Get-Field $result '__error'
if ($err) { throw "Rendering failed: $err" }
$size = Get-Field $result '__size'

$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('// Generated by tools\build-group-theme-art.ps1 from tools\group-theme-art\themes.js; do not edit by hand.')
[void]$sb.AppendLine('// Two white-on-transparent PNG layers per theme, shown with tintColor: `lines` (strokes) and `fills` (filled shapes).')
[void]$sb.AppendLine("import type { GroupThemeId } from '../types';")
[void]$sb.AppendLine('')
[void]$sb.AppendLine('/** Pixel size of every layer; the drawing is 244 x 96 units, so the aspect ratio is 244 / 96. */')
[void]$sb.AppendLine(('export const THEME_ART_SIZE = {{ width: {0}, height: {1} }};' -f $size[0], $size[1]))
[void]$sb.AppendLine('')
[void]$sb.AppendLine('export interface ThemeArt {')
[void]$sb.AppendLine('  lines: string;')
[void]$sb.AppendLine('  fills: string;')
[void]$sb.AppendLine('}')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('export const THEME_ART: Record<GroupThemeId, ThemeArt> = {')
foreach ($id in $ids) {
    $art = Get-Field $result $id
    if (-not $art) { throw "No drawing for $id" }
    [void]$sb.AppendLine("  ${id}: {")
    [void]$sb.AppendLine("    lines: '$($art.lines)',")
    [void]$sb.AppendLine("    fills: '$($art.fills)',")
    [void]$sb.AppendLine('  },')
}
[void]$sb.AppendLine('};')
Write-Utf8File $target $sb.ToString()
$kb = [math]::Round((Get-Item -LiteralPath $target).Length / 1024, 1)
Write-Host "Wrote $target ($kb KB, layers $($size[0]) x $($size[1]))."
